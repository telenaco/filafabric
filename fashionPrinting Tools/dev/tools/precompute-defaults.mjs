import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { gzipSync } from 'node:zlib';
import { DESIGNS } from '../../site/src/ui/designs.js';
import { generateDesignExportAsync } from '../../site/src/engine/design-export.js';
import { defaultCacheIdentity, referenceCacheIdentity, stringifyDefaultResult } from '../../site/src/engine/default-cache-format.js';
import { importProfiles } from '../../site/src/engine/profile-import.js';
import { toTextile, ADVANCED_DEFAULTS, PRIMARY_DEFAULTS } from '../../site/src/ui/controls.js';

export const root = fileURLToPath(new URL('../../', import.meta.url));
const sha = bytes => createHash('sha256').update(bytes).digest('hex');
export function defaultCacheRevision() {
  const files = [];
  const walk = dir => { for (const name of fs.readdirSync(path.join(root, dir))) { const file = `${dir}/${name}`; if (fs.statSync(path.join(root,file)).isDirectory()) walk(file); else if (/\.js$/.test(file) && !file.endsWith('/precomputed-version.js')) files.push(file); } };
  walk('site/src');
  files.push('dev/tools/precompute-defaults.mjs','site/vendor/tactile/tactile.js','site/vendor/three/three.module.js','site/vendor/arachne/provenance.json');
  return sha(files.sort().map(file => `${file}\0${fs.readFileSync(path.join(root,file),'utf8').replace(/\r\n/g,'\n')}\0`).join(''));
}
export function defaultInput(card) {
  const read = (kind, id) => { const name = `${id}.json`; return importProfiles(fs.readFileSync(path.join(root,`site/profiles/${kind}/${name}`),'utf8'),name)[kind][0]; };
  const machine = read('machines','prusa-mk3s'), material = read('materials','filaflex-95-foamy');
  material.print_defaults = { ...material.print_defaults, layer_height: 0.2 };
  const own = card.sanitize(card.defaults());
  card.setSize?.(own,100,100);
  return { machine,material,design:card.id,settings:card.id === 'loop-pile' ? toTextile(own,ADVANCED_DEFAULTS) : own,width:100,height:100,
    outline:null,vector:null,regions:null,shapeOutline:false,solidLayers:1,solidGenerator:'arachne',extraLayers:0,brim:2,perimeters:2,meshPerimeters:0,backing:null,image:null,
    pilePattern:PRIMARY_DEFAULTS.pattern,pilePatternScale:PRIMARY_DEFAULTS.patternScale };
}

export async function precomputeDefaults() {
  const revision = defaultCacheRevision(), folder = path.join(root,'site/precomputed'), entries = {};
  const old = fs.existsSync(path.join(folder,'index.json')) ? JSON.parse(fs.readFileSync(path.join(folder,'index.json'),'utf8')) : null;
  fs.mkdirSync(path.join(folder,revision.slice(0,16)),{recursive:true});
  for (const card of DESIGNS.filter(c => c.status === 'ready' && !c.hidden)) {
    const input = defaultInput(card), inputKey = sha(defaultCacheIdentity(input)), start = performance.now();
    const result = await generateDesignExportAsync(input);
    const data = Buffer.from(stringifyDefaultResult({ format:1,revision,inputKey,result }));
    const compressed = gzipSync(data,{level:9}), file = `${revision.slice(0,16)}/${card.id}.${inputKey.slice(0,16)}.json.gz`;
    fs.writeFileSync(path.join(folder,file),compressed);
    entries[inputKey] = { design:card.id,referenceKey:sha(referenceCacheIdentity(input)),file,dataSha256:sha(data),bytes:compressed.length };
    console.log(`${card.id}: ${Math.round(performance.now()-start)} ms -> ${Math.round(compressed.length/1024)} KB`);
  }
  fs.writeFileSync(path.join(folder,'index.json'),JSON.stringify({format:1,revision,entries},null,2)+'\n');
  fs.writeFileSync(path.join(root,'site/src/ui/precomputed-version.js'),`// Generated by npm run precompute. A source-fingerprint test guards stale default toolpaths.\nexport const PRECOMPUTED_REVISION = '${revision}';\n`);
  for (const entry of Object.values(old?.entries ?? {})) if (!Object.values(entries).some(e=>e.file===entry.file) && /^[a-f0-9]{16}\/[a-z0-9-]+\.[a-f0-9]{16}\.json\.gz$/.test(entry.file)) fs.rmSync(path.join(folder,entry.file),{force:true});
  console.log(JSON.stringify({cards:Object.keys(entries).length,compressedMB:+(Object.values(entries).reduce((n,e)=>n+e.bytes,0)/1e6).toFixed(2),revision}));
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await precomputeDefaults();
