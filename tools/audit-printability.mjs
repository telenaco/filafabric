import fs from 'node:fs';
import { DESIGNS } from '../src/ui/designs.js';
import { generate } from '../src/engine/generate.js';
import { generateSquiggle } from '../src/engine/squiggle.js';
import { toTextile } from '../src/ui/controls.js';
import { printabilityScore } from '../src/ui/printability.js';
const profile = (kind, id) => JSON.parse(fs.readFileSync(new URL(`../profiles/${kind}/${id}.json`, import.meta.url)));
const machine = profile('machines', 'prusa-mk3s'), material = profile('materials', 'filaflex-95-foamy');
const entries = [];
for (const d of DESIGNS.filter((d) => ['ready', 'preset'].includes(d.status))) {
  const id = d.opens?.design ?? d.id, target = DESIGNS.find((m) => m.id === id);
  const settings = { ...target.defaults(), ...d.opens?.patch };
  const r = id === 'loop-pile' ? generate(machine, material, toTextile(settings)) : id === 'squiggle' ? generateSquiggle(machine, material, settings) : target.generate(machine, material, settings);
  entries.push({ id: d.id, score: printabilityScore(r), ...r.fabric, hops: r.stats.hops, moves: r.stats.moves, clearanceFlags: r.stats.violations, routing: r.routing ?? null });
}
entries.sort((a, b) => a.score - b.score || a.id.localeCompare(b.id));
fs.writeFileSync(new URL('../src/ui/printability-data.js', import.meta.url), `// Generated by node tools/audit-printability.mjs. Geometry estimates, not physical qualification.\nexport const PRINTABILITY = ${JSON.stringify(entries, null, 2)};\n`);
console.log(entries.map((e, i) => `${i + 1}. ${e.id}: ${e.score.toFixed(1)}`).join('\n'));
