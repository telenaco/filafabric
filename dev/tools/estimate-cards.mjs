// Pre-computes what every card prints as at its default 100 x 100 mm, and again for each of its "Start from" presets, so the
// library can show time, filament and layers at once, without generating any G-code while someone browses.
// Run: node dev/tools/estimate-cards.mjs   (a few minutes; writes site/src/ui/card-estimates.js)
// Only three numbers per card are kept, so the file is about 15 KB and loads with the page. The G-code is not stored.
import fs from 'node:fs';
import { DESIGNS } from '../../site/src/ui/designs.js';
import { generate } from '../../site/src/engine/generate.js';
import { generateSquiggle, SAMPLERS } from '../../site/src/engine/squiggle.js';
import { toTextile } from '../../site/src/ui/controls.js';
import { printTimeSeconds } from '../../site/src/ui/print-estimates.js';

const profile = (kind, id) => JSON.parse(fs.readFileSync(new URL(`../../site/profiles/${kind}/${id}.json`, import.meta.url)));
const machine = profile('machines', 'prusa-mk3s'), material = profile('materials', 'filaflex-95-foamy');

const run = (design, settings) => {
  if (design.id === 'loop-pile') return generate(machine, material, toTextile(settings));
  if (design.id === 'squiggle') {
    const { width, height, mode, shape, spacing, amplitude, wavelength, colorChange, pattern } = settings;
    return generateSquiggle(machine, material, { width, height, mode, shape, spacing, amplitude, wavelength, colorChange, sampler: SAMPLERS[pattern] ?? SAMPLERS.centerSpot, outline: null });
  }
  return design.generate(machine, material, settings, {});
};

/** The three numbers a card tile shows. */
export function summarise(result) {
  const seconds = printTimeSeconds(result.stats);
  const layers = result.layerCount ?? new Set(result.strands.map((strand) => strand.layer ?? (strand.kind === 'base' ? 0 : 1))).size;
  return {
    min: seconds === null ? null : Math.round(seconds / 60 * (seconds < 600 ? 10 : 1)) / (seconds < 600 ? 10 : 1),
    g: Math.round(result.stats.filamentGrams * 100) / 100,
    layers: Math.max(1, layers),
  };
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].replaceAll('\\', '/').split('/').pop())) {
  const out = {};
  for (const design of DESIGNS.filter((card) => card.status === 'ready' && !card.hidden)) {
    const base = design.defaults();
    if (design.setSize) design.setSize(base, 100, 100); else Object.assign(base, { width: 100, height: 100 });
    const cases = [[design.id, base], ...(design.presets ?? []).map((preset) => {
      const settings = design.sanitize({ ...base, ...preset.patch });
      if (design.setSize) design.setSize(settings, 100, 100);
      return [`${design.id}:${preset.id}`, settings];
    })];
    for (const [key, settings] of cases) {
      try { out[key] = summarise(run(design, settings)); process.stdout.write(`${key} ${JSON.stringify(out[key])}\n`); }
      catch (error) { process.stdout.write(`${key} skipped: ${error.message.slice(0, 80)}\n`); }
    }
  }
  const body = Object.entries(out).map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)},`).join('\n');
  fs.writeFileSync(new URL('../../site/src/ui/card-estimates.js', import.meta.url), `// Generated by node dev/tools/estimate-cards.mjs. What each card, and each of its presets, prints as at 100 x 100 mm on the Prusa MK3S with Foamy 95A: minutes (the motion estimate), grams of filament and print layers. Estimates, not measurements.\nexport const CARD_ESTIMATES = Object.freeze({\n${body}\n});\n`);
  process.stdout.write(`Wrote ${Object.keys(out).length} estimates.\n`);
}
